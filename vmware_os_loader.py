    def check_existing_auth_file(self):
        fpath = os.path.join(TMP_DIR, "auth_success.enc")
        if os.path.exists(fpath):
            try:
                with open(fpath, "r") as f:
                    hex_str = f.read().strip()
                dec = decrypt_aes128_hex(hex_str)
                if "true" in dec.lower():
                    self.latest_auth_status = True
                    try:
                        data = json.loads(dec)
                        self.latest_user_name = data.get("user_name", "Verified User")
                    except Exception:
                        self.latest_user_name = "Verified User"
                    self.latest_auth_time = datetime.now().strftime("%H:%M:%S")
            except Exception:
                pass

    def on_auth_file_received(self, filename, hex_content, client_ip):
        decrypted = decrypt_aes128_hex(hex_content)
        is_success = "success" in filename.lower() or "true" in decrypted.lower()

        if is_success:
            self.latest_auth_status = True
            try:
                data = json.loads(decrypted)
                self.latest_user_name = data.get("user_name", "Verified User")
            except Exception:
                self.latest_user_name = "Verified User"
            self.latest_auth_time = datetime.now().strftime("%H:%M:%S")

            self.after(0, lambda: self.auth_badge.configure(
                text=f"🟢 ESP Auth: Verified ({self.latest_user_name})",
                fg_color=self.COLORS["success_bg"],
                text_color=self.COLORS["success"]
            ))
        else:
            self.latest_auth_status = False
            self.latest_user_name = "Denied"
            self.latest_auth_time = datetime.now().strftime("%H:%M:%S")

            self.after(0, lambda: self.auth_badge.configure(
                text="🔴 ESP Auth: Access Denied",
                fg_color=self.COLORS["danger_bg"],
                text_color=self.COLORS["danger"]
            ))

        self.after(0, self.update_auth_telemetry_ui)

