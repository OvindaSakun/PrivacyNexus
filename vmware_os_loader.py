def find_vmware_tool(tool_name="vmrun.exe"):
    """Locates vmrun.exe or vmware-vdiskmanager.exe on Windows."""
    # 1. Check system PATH
    found = shutil.which(tool_name)
    if found:
        return found

    # 2. Check standard installation folders
    for base_path in VMWARE_SEARCH_PATHS:
        dir_path = os.path.dirname(base_path)
        target = os.path.join(dir_path, tool_name)
        if os.path.exists(target):
            return target

    return ""

def decrypt_aes128_hex(hex_str):
    """Decrypts AES-128-CBC hex payload generated by ESP32."""
    try:
        cipher_bytes = bytes.fromhex(hex_str.strip())
        cipher = AES.new(AES_KEY, AES.MODE_CBC, AES_IV)
        decrypted = cipher.decrypt(cipher_bytes)
        pad_len = decrypted[-1]
        if pad_len <= 16:
            decrypted = decrypted[:-pad_len]
        return decrypted.decode('utf-8', errors='ignore')
    except Exception as e:
        return f"Decryption Error: {e}"

