    def get_running_vmx_list(self):
        """Query running VMs via vmrun list command."""
        running = []
        if not self.vmrun_path or not os.path.exists(self.vmrun_path):
            return running

        for target in ["ws", "player"]:
            try:
                cmd = [self.vmrun_path, "-T", target, "list"]
                output = subprocess.check_output(cmd, stderr=subprocess.DEVNULL, text=True)
                for line in output.splitlines():
                    if line.endswith(".vmx"):
                        running.append(os.path.normpath(line.strip()))
                break
            except Exception:
                continue
        return running

