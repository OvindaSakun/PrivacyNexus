from http.server import HTTPServer, BaseHTTPRequestHandler

class EmbeddedHTTPAuthReceiver:
    def __init__(self, callback):
        self.callback = callback
        self.running = True

        self.t1 = threading.Thread(target=self._run_http_server, args=(5000,), daemon=True)
        self.t2 = threading.Thread(target=self._run_http_server, args=(2222,), daemon=True)
        self.t3 = threading.Thread(target=self._poll_hotspot, daemon=True)

    def start(self):
        self.t1.start()
        self.t2.start()
        self.t3.start()

    def _save_and_notify(self, filename, hex_content, client_ip):
        filepath = os.path.join(TMP_DIR, filename)
        try:
            with open(filepath, "w") as f:
                f.write(hex_content)
            if self.callback:
                self.callback(filename, hex_content, client_ip)
        except Exception as e:
            print(f"Error saving auth file: {e}")

    def _run_http_server(self, port):
        callback_ref = self._save_and_notify

        class Handler(BaseHTTPRequestHandler):
            def do_POST(self):
                try:
                    length = int(self.headers.get('Content-Length', 0))
                    body = self.rfile.read(length).decode('utf-8', errors='ignore')
                    filename = "auth_status.enc"
                    hex_content = ""
                    try:
                        data = json.loads(body)
                        filename = data.get("filename", "auth_status.enc")
                        hex_content = data.get("data", "")
                    except Exception:
                        hex_content = body.strip()

                    if "success" in filename.lower():
                        filename = "auth_success.enc"
                    elif "false" in filename.lower():
                        filename = "auth_false.enc"

                    callback_ref(filename, hex_content, self.client_address[0])
                    self.send_response(200)
                    self.end_headers()
                except Exception:
                    self.send_response(500)
                    self.end_headers()

            def log_message(self, format, *args):
                pass

        try:
            httpd = HTTPServer(('0.0.0.0', port), Handler)
            httpd.serve_forever()
        except Exception:
            pass

    def _poll_hotspot(self):
        last_hex = ""
        while self.running:
            try:
                req = urllib.request.Request("http://192.168.4.1/", headers={'User-Agent': 'Mozilla/5.0'})
                with urllib.request.urlopen(req, timeout=1) as response:
                    hex_content = response.read().decode('utf-8', errors='ignore').strip()
                    if hex_content and hex_content != last_hex:
                        last_hex = hex_content
                        dec = decrypt_aes128_hex(hex_content)
                        fn = "auth_success.enc" if "true" in dec.lower() else "auth_false.enc"
                        self._save_and_notify(fn, hex_content, "192.168.4.1")
            except Exception:
                pass
            time.sleep(2)

