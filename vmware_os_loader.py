    def start_vm_guarded(self, vmx_path, vm_name):
        """Verifies ESP32 Fingerprint Auth File, launches VM, and DELETES the auth file."""
        # Check latest auth file state
        self.check_existing_auth_file()

        if not self.latest_auth_status:
            messagebox.showerror(
                "Access Denied - Fingerprint Required",
                f"Cannot start Virtual Machine '{vm_name}'!\n\n"
                "🔒 ESP32 Fingerprint Verification is REQUIRED.\n"
                "Please touch an enrolled finger on the ESP32 scanner to unlock VM execution."
            )
            return

        user_name = self.latest_user_name
        launched = False
        vm_dir = os.path.dirname(self.vmrun_path) if self.vmrun_path else ""

        # 1. Try launching direct VMware Workstation / Player GUI executable in a separate window
        if vm_dir and os.path.exists(vm_dir):
            vmware_exe = os.path.join(vm_dir, "vmware.exe")
            vmplayer_exe = os.path.join(vm_dir, "vmplayer.exe")

            if os.path.exists(vmware_exe):
                try:
                    subprocess.Popen([vmware_exe, vmx_path])
                    launched = True
                except Exception:
                    pass

            if not launched and os.path.exists(vmplayer_exe):
                try:
                    subprocess.Popen([vmplayer_exe, vmx_path])
                    launched = True
                except Exception:
                    pass

        # 2. Try vmrun start command
        if not launched and self.vmrun_path and os.path.exists(self.vmrun_path):
            for target in ["ws", "player"]:
                try:
                    cmd = [self.vmrun_path, "-T", target, "start", vmx_path, "gui"]
                    subprocess.Popen(cmd)
                    launched = True
                    break
                except Exception:
                    continue

        # 3. Fallback: Native Windows file association (opens VMware in a separate window)
        if not launched:
            try:
                os.startfile(vmx_path)
                launched = True
            except Exception as e:
                messagebox.showerror("VM Launch Error", f"Could not launch VMware window for '{vm_name}':\n{e}")
                return

        if launched:
            # Delete authentication file from C:\tmp and reset auth status
            self.consume_and_delete_auth_files()

            messagebox.showinfo(
                "VM Starting",
                f"🟢 Fingerprint Verified ({user_name})!\n\n"
                "Authentication token consumed and deleted from C:\\tmp.\n"
                f"Opening VMware in a separate window for '{vm_name}'..."
            )
            self.after(3000, self.refresh_vm_list)

    def consume_and_delete_auth_files(self):
        """Deletes authentication files from C:\tmp and resets status."""
        for fn in ["auth_success.enc", "auth_false.enc", "auth_status.enc"]:
            fpath = os.path.join(TMP_DIR, fn)
            if os.path.exists(fpath):
                try:
                    os.remove(fpath)
                except Exception:
                    pass

        self.latest_auth_status = False
        self.latest_user_name = "Consumed / Expired"
        self.latest_auth_time = datetime.now().strftime("%H:%M:%S (Deleted)")

        self.auth_badge.configure(
            text="🔒 ESP Auth: Pending Scan",
            fg_color=self.COLORS["danger_bg"],
            text_color=self.COLORS["danger"]
        )
        self.update_auth_telemetry_ui()

    def control_vm(self, vmx_path, action="stop", mode="hard"):
        success = False

        if self.vmrun_path and os.path.exists(self.vmrun_path):
            for target in ["ws", "player"]:
                for m in [mode, "hard", "soft"]:
                    try:
                        cmd = [self.vmrun_path, "-T", target, action, vmx_path, m]
                        res = subprocess.run(cmd, capture_output=True, text=True, timeout=5)
                        if res.returncode == 0:
                            success = True
                            break
                    except Exception:
                        continue
                if success:
                    break

        # Process fallback kill on Windows if vmrun soft mode failed
        if not success and action == "stop":
            try:
                import psutil
                vmx_filename = os.path.basename(vmx_path).lower()
                for proc in psutil.process_iter(['pid', 'name', 'cmdline']):
                    if proc.info['name'] and 'vmware-vmx' in proc.info['name'].lower():
                        cmdline = " ".join(proc.info['cmdline'] or []).lower()
                        if vmx_filename in cmdline:
                            proc.kill()
                            success = True
            except Exception:
                pass

        if success or action == "stop":
            messagebox.showinfo("VM Control", f"Executed '{action}' ({mode}) command for Virtual Machine!")
        else:
            messagebox.showerror("VM Control Error", f"Could not execute '{action}' command for VM.")

        self.after(2000, self.refresh_vm_list)

    def delete_vm(self, vm_name):
        if messagebox.askyesno("Confirm Delete", f"Are you sure you want to delete VM '{vm_name}' from HDD directory?"):
            folder_path = os.path.join(HDD_DIR, vm_name)
            try:
                shutil.rmtree(folder_path)
                messagebox.showinfo("Deleted", f"Virtual Machine '{vm_name}' removed from HDD folder.")
                self.refresh_vm_list()
            except Exception as e:
                messagebox.showerror("Delete Error", str(e))

