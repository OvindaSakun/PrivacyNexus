AES_KEY = b'MySecr3tAESKey!!'  # 16 bytes matching ESP32
AES_IV  = bytes(range(16))     # 0x00..0x0F matching ESP32
TARGET_DIR = r"C:\tmp"
PORTS = [5000, 2222]

os.makedirs(TARGET_DIR, exist_ok=True)

def decrypt_aes128_hex(hex_str):
    """Decrypts AES-128-CBC hex payload generated by ESP32."""
    try:
        cipher_bytes = bytes.fromhex(hex_str.strip())
        cipher = AES.new(AES_KEY, AES.MODE_CBC, AES_IV)
        decrypted = cipher.decrypt(cipher_bytes)
        # Remove PKCS7 padding
        pad_len = decrypted[-1]
        if pad_len <= 16:
            decrypted = decrypted[:-pad_len]
        return decrypted.decode('utf-8', errors='ignore')
    except Exception as e:
        return f"Decryption Error: {e}"

last_processed_hex = ""

def process_received_file(filename, hex_content, client_ip, method_label):
    global last_processed_hex
    if not hex_content or hex_content == last_processed_hex:
        return
    
    last_processed_hex = hex_content
    filepath = os.path.join(TARGET_DIR, filename)
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    # Save raw file to C:\tmp
    with open(filepath, "w") as f:
        f.write(hex_content)

    # Decrypt content
    decrypted_json = decrypt_aes128_hex(hex_content)

    print("\n" + "=" * 65)
    print(f" [+] [{timestamp}] FILE RECEIVED via {method_label}")
    print("=" * 65)
    print(f" Source Device IP : {client_ip}")
    print(f" Saved File Path  : {filepath}")
    print(f" Raw Encrypted Hex: {hex_content[:48]}...")
    print("-" * 65)
    print(" [*] DECRYPTED AES-128 JSON PAYLOAD:")
    print(f" {decrypted_json}")
    print("=" * 65 + "\n")

