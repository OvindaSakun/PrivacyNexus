# HTTP Request Handler
# ==============================================================================
class AuthFileHTTPRequestHandler(BaseHTTPRequestHandler):
    def do_POST(self):
        try:
            length = int(self.headers.get('Content-Length', 0))
            body = self.rfile.read(length).decode('utf-8', errors='ignore')

            filename = "auth_status.enc"
            hex_content = ""

            try:
                data = json.loads(body)
                filename = data.get("filename", "auth_status.enc")
                hex_content = data.get("data", "")
            except Exception:
                hex_content = body.strip()

            if "success" in filename.lower():
                filename = "auth_success.enc"
            elif "false" in filename.lower():
                filename = "auth_false.enc"

            client_ip = self.client_address[0]
            server_port = self.server.server_port

            process_received_file(filename, hex_content, client_ip, f"HTTP POST Port {server_port}")

            # Send HTTP 200 Response
            self.send_response(200)
            self.send_header('Content-Type', 'application/json')
            self.send_header('Access-Control-Allow-Origin', '*')
            self.end_headers()
            self.wfile.write(b'{"status":"success","message":"File saved to C:\\\\tmp"}')

        except Exception as e:
            print(f"[!] Error handling HTTP POST request: {e}")
            self.send_response(500)
            self.end_headers()

    def log_message(self, format, *args):
        # Silence default HTTP server logging for cleaner console output
        pass

# ==============================================================================
# Server Runners (HTTP Server, UDP Broadcast Listener & Poller)
# ==============================================================================
def start_http_server_on_port(port):
    try:
        httpd = HTTPServer(('0.0.0.0', port), AuthFileHTTPRequestHandler)
        print(f" [*] HTTP POST Server active on port {port}")
        httpd.serve_forever()
    except Exception as e:
        print(f" [!] Could not bind HTTP Server on port {port}: {e}")

def start_udp_listener_on_port(port):
    udp_sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    udp_sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    try:
        udp_sock.bind(("0.0.0.0", port))
        print(f" [*] UDP Broadcast Listener active on port {port}")
    except Exception as e:
        print(f" [!] Could not bind UDP listener on port {port}: {e}")
        return

    while True:
        try:
            data, addr = udp_sock.recvfrom(8192)
            text = data.decode('utf-8', errors='ignore').strip()
            if text.startswith("SCP_TRANSFER"):
                parts = text.split(" ", 2)
                if len(parts) >= 3:
                    filename = parts[1]
                    hex_content = parts[2]
                    process_received_file(filename, hex_content, addr[0], f"UDP Hotspot Broadcast Port {port}")
        except Exception:
            time.sleep(0.1)

def poll_esp32_http_endpoint():
    print(" [*] ESP32 Wi-Fi Hotspot HTTP Poller active (http://192.168.4.1/)...")
    while True:
        try:
            req = urllib.request.Request("http://192.168.4.1/", headers={'User-Agent': 'Mozilla/5.0'})
            with urllib.request.urlopen(req, timeout=1) as response:
                hex_content = response.read().decode('utf-8', errors='ignore').strip()
                if hex_content and hex_content != last_processed_hex:
                    filename = "auth_success.enc" if "true" in decrypt_aes128_hex(hex_content).lower() else "auth_false.enc"
                    process_received_file(filename, hex_content, "192.168.4.1", "HTTP Hotspot Endpoint")
        except Exception:
            pass
        time.sleep(2)

