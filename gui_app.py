# ==============================================================================
# Embedded HTTP POST File Receiver Server
# ==============================================================================
class HTTPAuthPostReceiver:
    def __init__(self, callback_file_received):
        self.callback = callback_file_received
        self.running = True

        self.t1 = threading.Thread(target=self._run_http_server, args=(5000,), daemon=True)
        self.t2 = threading.Thread(target=self._run_http_server, args=(2222,), daemon=True)

    def start(self):
        self.t1.start()
        self.t2.start()

    def _save_and_notify(self, filename, hex_content, client_ip, method):
        filepath = os.path.join(TARGET_DIR, filename)
        try:
            with open(filepath, "w") as f:
                f.write(hex_content)
            print(f"[{method}] Received {filename} from {client_ip}")
            if self.callback:
                self.callback(filename, hex_content, client_ip)
        except Exception as e:
            print(f"Error saving auth file from {method}: {e}")

    def _run_http_server(self, port):
        callback_ref = self._save_and_notify

        class RequestHandler(BaseHTTPRequestHandler):
            def do_POST(self):
                try:
                    length = int(self.headers.get('Content-Length', 0))
                    body = self.rfile.read(length).decode('utf-8', errors='ignore')
                    
                    filename = "auth_status.enc"
                    hex_content = ""
                    
                    try:
                        data = json.loads(body)
                        filename = data.get("filename", "auth_status.enc")
                        hex_content = data.get("data", "")
                    except Exception:
                        hex_content = body.strip()

                    if "success" in filename.lower():
                        filename = "auth_success.enc"
                    elif "false" in filename.lower():
                        filename = "auth_false.enc"

                    callback_ref(filename, hex_content, self.client_address[0], f"HTTP POST Port {port}")

                    self.send_response(200)
                    self.send_header('Content-Type', 'application/json')
                    self.end_headers()
                    self.wfile.write(b'{"status":"success"}')
                except Exception as e:
                    self.send_response(500)
                    self.end_headers()

            def log_message(self, format, *args):
                pass

        try:
            httpd = HTTPServer(('0.0.0.0', port), RequestHandler)
            httpd.serve_forever()
        except Exception as e:
            print(f"HTTP Server port {port} error: {e}")

