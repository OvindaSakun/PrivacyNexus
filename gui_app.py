    def get_serial_ports(self):
        ports = [port.device for port in serial.tools.list_ports.comports()]
        return ports if ports else ["No Ports Found"]

    def refresh_serial_ports(self):
        ports = self.get_serial_ports()
        self.port_combo.configure(values=ports)
        if ports:
            self.port_combo.set(ports[0])

    def toggle_serial_connection(self):
        if self.serial_running:
            self.serial_running = False
            if self.serial_conn and self.serial_conn.is_open:
                self.serial_conn.close()
            self.btn_connect.configure(text="Connect ESP32", fg_color=self.COLORS["primary"])
            self.lock_status_label.configure(text="● Disconnected from ESP32 Serial", text_color=self.COLORS["danger"])
            return

        port = self.port_combo.get()
        if not port or port == "No Ports Found":
            messagebox.showerror("Serial Error", "Please select a valid COM port!")
            return

        try:
            self.serial_conn = serial.Serial(port, 115200, timeout=1)
            self.serial_running = True
            self.serial_thread = threading.Thread(target=self.read_serial_loop, daemon=True)
            self.serial_thread.start()

            self.heartbeat_thread = threading.Thread(target=self.heartbeat_loop, daemon=True)
            self.heartbeat_thread.start()

            self.btn_connect.configure(text="Disconnect 🔌", fg_color=self.COLORS["danger"])
            self.lock_status_label.configure(text=f"● Connected to {port} (Checking stored templates...)", text_color=self.COLORS["primary"])
            self.send_serial_cmd("ping")
            self.send_serial_cmd("l")
        except Exception as e:
            messagebox.showerror("Serial Connection Error", str(e))

    def heartbeat_loop(self):
        while self.serial_running and self.serial_conn and self.serial_conn.is_open:
            time.sleep(3)
            if self.serial_running:
                self.send_serial_cmd("ping")

    def send_serial_cmd(self, cmd):
        if self.serial_conn and self.serial_conn.is_open:
            try:
                self.serial_conn.write((cmd + "\n").encode('utf-8'))
            except Exception:
                pass

    def read_serial_loop(self):
        while self.serial_running and self.serial_conn and self.serial_conn.is_open:
            try:
                line = self.serial_conn.readline().decode('utf-8', errors='ignore').strip()
                if line:
                    self.after(0, self.handle_serial_data, line)
            except Exception:
                break

    def handle_serial_data(self, line):
        self.append_log(f"ESP32 -> {line}")
        try:
            data = json.loads(line)
            event = data.get("event", "")

            # Verification Event
            if event == "verify":
                status = data.get("status", "")
                confidence = data.get("confidence", 0)
                if status == "success":
                    uid = data.get("id", 0)
                    uname = data.get("name", "User")
                    self.lock_icon_label.configure(text="🔓")
                    self.lock_status_label.configure(
                        text=f"● Verification Success! Welcome {uname}",
                        text_color=self.COLORS["success"]
                    )
                    self.add_login_log_entry(uid, uname, "SUCCESS", confidence, "auth_success.enc")
                    if not self.is_authenticated:
                        self.after(500, lambda: self.unlock_dashboard(uname))
                else:
                    self.lock_icon_label.configure(text="🔒")
                    self.lock_status_label.configure(
                        text="● Verification Failed! Access Denied.",
                        text_color=self.COLORS["danger"]
                    )
                    self.add_login_log_entry(None, "Unrecognized Finger", "FAILED", 0, "auth_false.enc")

            # Pong Heartbeat / Status Event
            elif event == "pong":
                count = data.get("count", -1)
                stations = data.get("stations", [])
                stations_count = data.get("stations_count", len(stations))

                self.ap_badge.configure(text=f"📡 ESP32 AP: 192.168.4.1 ({stations_count} Connected)")
                self.render_connected_devices_table(stations)

                if count == 0 and not self.is_authenticated:
                    self.lock_icon_label.configure(text="🔓")
                    self.lock_status_label.configure(
                        text="● No registered fingerprints found. Direct access granted!",
                        text_color=self.COLORS["success"]
                    )
                    self.after(500, lambda: self.unlock_dashboard("Setup User (No Fingerprints Enrolled)"))

            # Enroll Interactive Steps Event
            elif event == "enroll_status":
                step = data.get("step", "")
                msg = data.get("msg", "")
                if step == "place_1":
                    self.enroll_step_icon.configure(text="👆")
                    self.enroll_step_title.configure(text="Step 1: Place Finger")
                    self.enroll_step_msg.configure(text=msg)
                elif step == "remove":
                    self.enroll_step_icon.configure(text="🖐️")
                    self.enroll_step_title.configure(text="Step 2: Remove Finger")
                    self.enroll_step_msg.configure(text=msg)
                elif step == "place_2":
                    self.enroll_step_icon.configure(text="👆")
                    self.enroll_step_title.configure(text="Step 3: Place Same Finger Again")
                    self.enroll_step_msg.configure(text=msg)
                elif step == "success":
                    self.enroll_step_icon.configure(text="✅")
                    self.enroll_step_title.configure(text="Enrollment Successful!")
                    self.enroll_step_msg.configure(text=f"Registered #{data.get('id')} ({data.get('name')})")
                    self.refresh_templates()
                elif step == "error":
                    self.enroll_step_icon.configure(text="❌")
                    self.enroll_step_title.configure(text="Enrollment Error")
                    self.enroll_step_msg.configure(text=msg)

            # Template List Event
            elif event == "list":
                templates = data.get("templates", [])
                count = data.get("count", len(templates))
                self.render_user_list(templates)
                if count == 0 and not self.is_authenticated:
                    self.lock_icon_label.configure(text="🔓")
                    self.lock_status_label.configure(
                        text="● No registered fingerprints found. Direct access granted!",
                        text_color=self.COLORS["success"]
                    )
                    self.after(500, lambda: self.unlock_dashboard("Setup User (No Fingerprints Enrolled)"))

        except json.JSONDecodeError:
            pass

