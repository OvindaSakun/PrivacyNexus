if getattr(sys, 'frozen', False):
    import builtins
    _orig_open = builtins.open
    def _custom_open(file, *args, **kwargs):
        try:
            file_str = os.fspath(file) if isinstance(file, (str, bytes, os.PathLike)) else str(file)
            if "customtkinter" in file_str and (".exe" in file_str or ".zip" in file_str):
                exe_dir = os.path.dirname(sys.executable)
                idx = file_str.find("customtkinter")
                if idx != -1:
                    file = os.path.join(exe_dir, file_str[idx:])
        except Exception:
            pass
        return _orig_open(file, *args, **kwargs)
    builtins.open = _custom_open

